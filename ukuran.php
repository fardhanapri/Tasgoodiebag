    /* ===== RENDER CARDS ===== */
    function renderSizes(filter = 'all') {
      const container = document.getElementById('sizeGridContainer');
      let html = '';
      const filtered = filter === 'all' ? SIZES : SIZES.filter(s => s.category === filter);
      
      if (filtered.length === 0) {
        html = `<div class="col-span-full text-center py-10">
          <i class="fas fa-box-open text-4xl text-muted/30 mb-3"></i>
          <p class="text-muted">Belum ada produk dalam kategori ini.</p>
        </div>`;
      } else {
        filtered.forEach((s, i) => {
          const delay = i * 50;
          html += `
            <a href="${s.page}" class="block group" data-aos="fade-up" data-aos-delay="${delay}">
              <div class="size-card bg-white rounded-2xl overflow-hidden p-5 text-center relative">
                <div class="card-badge">${s.gsm.join(' | ')} GSM</div>
                <div class="w-24 h-24 mx-auto bg-surface rounded-xl flex items-center justify-center mb-3 group-hover:bg-primary/5 transition-colors">
                  <img src="${s.img}" alt="${s.name}" class="max-h-16 object-contain">
                </div>
                <h3 class="text-lg font-extrabold text-dark">${s.name}</h3>
                <p class="text-sm text-muted">${s.size}</p>
                <div class="flex flex-wrap justify-center gap-1.5 mt-2">
                  ${s.gsm.map(g => `<span class="gsm-badge gsm-${g}">${g} GSM</span>`).join('')}
                </div>
                <p class="text-xs text-muted mt-2 line-clamp-2">${s.desc}</p>
                <div class="mt-3 inline-flex items-center gap-1 text-accent font-semibold text-sm group-hover:gap-2 transition-all">
                  Lihat Detail <i class="fas fa-arrow-right text-xs"></i>
                </div>
              </div>
            </a>
          `;
        });
      }
      container.innerHTML = html;
      AOS.refresh();
    }

    /* ===== FILTER ===== */
    window.filterCategory = function(type) {
      document.querySelectorAll('.category-tab').forEach(t => t.classList.remove('active'));
      document.querySelectorAll('.category-tab').forEach(t => {
        const btnType = t.textContent.toLowerCase().trim();
        if (type === 'all' && btnType === 'semua') {
          t.classList.add('active');
        } else if (btnType === type) {
          t.classList.add('active');
        }
      });
      renderSizes(type);
    };

    /* ===== INIT ===== */
    renderSizes('all');
  });
